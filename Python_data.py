# Python Data Types

# String
name = "John"

# Integer
age = 20

# Float
price = 99.99

# Boolean
is_active = True

# List
fruits = ["apple", "banana", "orange"]

# Tuple
colors = ("red", "green", "blue")

# Dictionary
student = {
    "name": "John",
    "age": 20
}

# Set
numbers = {1, 2, 3, 4}

print(type(name))
print(type(age))
print(type(price))
print(type(is_active))
print(type(fruits))
print(type(colors))
print(type(student))
print(type(numbers))

